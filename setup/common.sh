#!/usr/bin/env bash
# Shared helpers for setup scripts. Source this, don't execute it.
set -euo pipefail

C_G=$'\033[1;32m'; C_Y=$'\033[1;33m'; C_R=$'\033[1;31m'; C_0=$'\033[0m'
info() { printf '%s==>%s %s\n' "$C_G" "$C_0" "$*"; }
warn() { printf '%s==>%s %s\n' "$C_Y" "$C_0" "$*"; }
die()  { printf '%s==>%s %s\n' "$C_R" "$C_0" "$*" >&2; exit 1; }

# Repo root = parent of the directory this script was sourced from.
REPO_ROOT="$(cd "$(dirname "$(realpath "${BASH_SOURCE[1]}")")/.." && pwd)"
# shellcheck disable=SC1091
source "$REPO_ROOT/setup/envload.sh"

need() { command -v "$1" >/dev/null 2>&1 || die "missing required command: $1 (see setup/00-preflight.sh)"; }

# Escape \, & and | — the metacharacters on the replacement side of sed 's|...|VALUE|g'.
sed_escape_replacement() {
  local s="$1"
  s="${s//\\/\\\\}"
  s="${s//&/\\&}"
  s="${s//|/\\|}"
  printf '%s' "$s"
}

# Load .env into the environment and sanity-check the required values.
# Literal KEY=VALUE parse, never `source` — the parser (envload.sh) refuses
# anything docker compose or systemd would read differently, so the deploy
# scripts see exactly what the containers and units receive.
load_env() {
  [[ -f "$REPO_ROOT/.env" ]] || die ".env not found — run: make secrets"
  env_file_load "$REPO_ROOT/.env" \
    || die ".env has unparseable or unsafe lines — every line must be KEY=VALUE; values must not contain \$, backslashes or ' #' (see warnings above)"
  [[ -n "${NAMESILO_API_KEY:-}" && "${NAMESILO_API_KEY:-}" != "REPLACE_ME" ]] \
    || die "Set NAMESILO_API_KEY in .env (NameSilo → Domain Manager → API)"
  [[ -n "${ACME_EMAIL:-}" && "${ACME_EMAIL:-}" != "__ACME_EMAIL__" ]] \
    || die "Set ACME_EMAIL in .env"
  [[ -n "${PANEL_TOKEN:-}" && "${PANEL_TOKEN:-}" != "__PANEL_TOKEN__" ]] \
    || die "PANEL_TOKEN missing in .env — run: make secrets"
  # Authelia secrets (generated by make secrets); blanks would fail inside
  # the container instead of here.
  local v
  for v in AUTHELIA_SESSION_SECRET AUTHELIA_STORAGE_ENCRYPTION_KEY AUTHELIA_JWT_SECRET; do
    [[ -n "${!v:-}" && "${!v:-}" != "__${v}__" ]] \
      || die "$v missing in .env — run: make secrets (delete .env first to regenerate)"
  done
}

# Copy the raw lines for the given keys out of <target>/.env into a fresh
# root-owned 0600 <target>/.<name>.env (regenerated every run — never
# hand-edit). The ^KEY= pattern mirrors systemd's EnvironmentFile parser; on
# duplicates the last line wins in both. Absent keys simply don't appear.
derive_reduced_env() { # <target-dir> <name> [key...]
  local target="$1" name="$2" key tmp
  shift 2
  tmp="$(mktemp)"
  for key in "$@"; do
    # shellcheck disable=SC2024 # sudo is only for reading the 0600 .env; $tmp must stay user-owned
    sudo grep -E "^[[:space:]]*${key}[[:space:]]*=" "$target/.env" >>"$tmp" || true
  done
  sudo install -m 600 "$tmp" "$target/.$name.env"   # root:root 0600 — panel can't read it
  rm -f "$tmp"
}

# Reduced env file for panel-api.service: only the PANEL_* vars it reads.
# The service runs as uid 'panel' long-term, so anything in its environment
# is readable from /proc/<pid>/environ at that uid — the full .env would put
# the NameSilo key + Authelia secrets in that blast radius.
# Called from stack_sync_configs (make deploy / make update) AND 03-panel-api.sh
# (make api) so both install and rotate flows stay in sync with .env.
sync_panel_api_env() { # <target-dir> — derive <target>/.panel-api.env from <target>/.env
  local target="$1"
  derive_reduced_env "$target" panel-api "${panel_api_env_keys[@]}"   # key lists: envload.sh
  sudo grep -q '^[[:space:]]*PANEL_TOKEN[[:space:]]*=' "$target/.panel-api.env" \
    || warn "PANEL_TOKEN missing in $target/.env — panel-api will reject every request until it is set"
}

# Reduced env file for panel-ddns.service: only NAMESILO_API_KEY (+ optional
# DDNS_HOSTS). The oneshot runs as the SAME uid as panel-api, so while it runs
# its environ is readable by a panel-uid process — the full .env would sit in
# /proc/<pid>/environ for a few seconds per tick.
# The oneshot re-reads the file every tick, so a rotated key is picked up
# without a timer restart.
sync_ddns_env() { # <target-dir> — derive <target>/.panel-ddns.env from <target>/.env
  local target="$1"
  derive_reduced_env "$target" panel-ddns "${panel_ddns_env_keys[@]}"   # key lists: envload.sh
  sudo grep -q '^[[:space:]]*NAMESILO_API_KEY[[:space:]]*=' "$target/.panel-ddns.env" \
    || warn "NAMESILO_API_KEY missing in $target/.env — panel-ddns will FATAL on every tick until it is set"
}

# Idempotently ensure the non-root 'panel' user exists (runs the host API).
ensure_panel_user() {
  if ! id panel >/dev/null 2>&1; then
    info "Creating system user 'panel'"
    sudo useradd -r -s /usr/sbin/nologin -d /opt/panel-api panel
  fi
}

# ── Repo → deployed stack sync (make deploy / make update) ────────────────────
# The ONE place the repo's compose tree reaches /opt/panel and secrets are
# written into the deployed configs — first boot (02) and Day-2 updates (08)
# apply the identical sync. Idempotent. Requires load_env.
# Start-time-only configs (authelia's configuration.yml + users DB, traefik's
# static traefik.yml) are read only at container start: `up -d` recreates a
# service only when its compose *definition* changes, and neither service
# hot-reloads. So the sync snapshots those files first (STACK_CONFIG_SNAP) and
# stack_restart_if_configs_changed() — called AFTER `up -d` — restarts the
# affected services only if the content actually changed. (traefik/dynamic/ is
# exempt — the file provider hot-reloads it.)
stack_sync_configs() { # <target-dir>
  local target="$1"
  local f target_list repo_list
  if ! sudo docker network inspect edge >/dev/null 2>&1; then
    info "Creating external docker network 'edge'"
    sudo docker network create edge
  fi
  STACK_CONFIG_SNAP="$(mktemp -d)"
  trap 'rm -rf "$STACK_CONFIG_SNAP"' EXIT
  for f in authelia/configuration.yml authelia/users_database.yml traefik/traefik.yml \
           searxng/settings.yml; do
    if [[ -f "$target/$f" ]]; then
      sudo cp -p "$target/$f" "$STACK_CONFIG_SNAP/${f//\//_}"
    fi
  done
  info "Copying compose stack to $target (skipping node_modules/dist)"
  sudo mkdir -p "$target"
  tar -C "$REPO_ROOT/compose" --exclude=node_modules --exclude=dist -cf - . \
    | sudo tar -C "$target" -xf -
  # Remove managed configs deleted from the repo (tar overwrites but never
  # prunes). Scoped to traefik/: authelia/ holds runtime data (db.sqlite3 with
  # TOTP seeds, users_database.yml) and is never pruned.
  target_list="$(cd "$target/traefik" && find . -type f | sed 's|^\./||' | sort)"
  repo_list="$(cd "$REPO_ROOT/compose/traefik" && find . -type f | sed 's|^\./||' | sort)"
  [[ -n "$repo_list" ]] || die "repo traefik tree unexpectedly empty — aborting before touching $target"
  while IFS= read -r f; do
    if ! grep -Fxq -- "$f" <<<"$repo_list"; then
      info "Removing stale managed config: traefik/$f"
      sudo rm -f "$target/traefik/$f"
    fi
  done <<<"$target_list"

  # searxng/ — the deployed dir is a config ROOT, not a single file: SearXNG
  # reads settings.yml from it AND, if present, optional favicons.toml
  # (loaded at import by favicons.init()) and limiter.toml (lazy-loaded via
  # limiter.get_cfg() on every /config request) — a stale or renamed file
  # among those is LIVE config, not dead weight. Safe to prune: runtime data
  # lives in the named volume (/var/cache/searxng) and the bind is :ro.
  # Tolerates a missing dir (first landing: the tar below creates it).
  target_list="$(cd "$target/searxng" 2>/dev/null && find . -type f | sed 's|^\./||' | sort || true)"
  repo_list="$(cd "$REPO_ROOT/compose/searxng" && find . -type f | sed 's|^\./||' | sort)"
  [[ -n "$repo_list" ]] || die "repo searxng tree unexpectedly empty — aborting before touching $target"
  while IFS= read -r f; do
    [[ -n "$f" ]] || continue
    if ! grep -Fxq -- "$f" <<<"$repo_list"; then
      info "Removing stale managed config: searxng/$f"
      sudo rm -f "$target/searxng/$f"
    fi
  done <<<"$target_list"
  info "Writing secrets into deployed configs (repo copies keep placeholders)"
  local v_acme_email v_acme_ca v_panel_token v_searxng_secret
  v_acme_email="$(sed_escape_replacement "$ACME_EMAIL")"
  v_acme_ca="$(sed_escape_replacement "${ACME_CA_SERVER:-https://acme-v02.api.letsencrypt.org/directory}")"
  v_panel_token="$(sed_escape_replacement "$PANEL_TOKEN")"
  sudo sed -i \
    -e "s|__ACME_EMAIL__|${v_acme_email}|g" \
    -e "s|__ACME_CA_SERVER__|${v_acme_ca}|g" \
    -e "s|__PANEL_TOKEN__|${v_panel_token}|g" \
    "$target/traefik/traefik.yml" \
    "$target/traefik/dynamic/middlewares.yml"
  # The SearXNG instance secret. The container env carries no SEARXNG_SECRET
  # (that absence is what makes the deployed file's value win — env > file),
  # so the secret rides this sed exactly like the others. The value must be
  # usable BEFORE the substitution: an empty or placeholder value would be
  # written into the deployed file and the instance would sign cookies with
  # a public string.
  [[ -n "$SEARXNG_SECRET" && "$SEARXNG_SECRET" != __*__ ]] \
    || die "SEARXNG_SECRET missing or still a placeholder in .env — make secrets (fresh install) or add SEARXNG_SECRET=$(openssl rand -hex 32) to the repo .env (an existing .env predates this feature)"
  if [[ -f "$target/searxng/settings.yml" ]]; then
    v_searxng_secret="$(sed_escape_replacement "$SEARXNG_SECRET")"
    sudo sed -i -e "s|__SEARXNG_SECRET__|${v_searxng_secret}|g" "$target/searxng/settings.yml"
  fi
  if sudo grep -RqE '__ACME_EMAIL__|__ACME_CA_SERVER__|__PANEL_TOKEN__|__SEARXNG_SECRET__' "$target/traefik" "$target/searxng" "$target/docker-compose.yml" 2>/dev/null; then
    die "secret substitution failed — placeholders remain under $target"
  fi
  sudo install -m 600 "$REPO_ROOT/.env" "$target/.env"
  # Re-derive the panel-uid reduced env files so an .env edit stays one-shot.
  sync_panel_api_env "$target"
  sync_ddns_env "$target"
  sudo chmod 600 "$target/traefik/dynamic/middlewares.yml"   # contains PANEL_TOKEN
  # The deployed settings.yml carries the instance secret — tar restores the
  # repo's root:root 0644 on every sync, so BOTH lines run every sync: the
  # chown because the app reads it as uid 977 at import (root:root 0600
  # would be EACCES → crashloop), the chmod for confidentiality.
  if [[ -f "$target/searxng/settings.yml" ]]; then
    sudo chown 977:977 "$target/searxng/settings.yml"
    sudo chmod 600 "$target/searxng/settings.yml"
  fi
  if [[ ! -f "$target/authelia/users_database.yml" ]]; then
    die "authelia/users_database.yml missing (fresh clone? it's gitignored — hashes stay off GitHub).

Create it from the template:
  cp compose/authelia/users_database.yml.example compose/authelia/users_database.yml
…then generate a hash per user (docs/RUNBOOK.md → Phase 1) and re-run."
  fi
  if sudo grep -q 'REPLACE_WITH_ARGON2_HASH' "$target/authelia/users_database.yml"; then
    die "authelia/users_database.yml still has placeholder passwords.

Generate a hash for each user:
  docker run --rm authelia/authelia:4 authelia crypto hash generate argon2 --password 'YOUR-PASSWORD'

…then edit compose/authelia/users_database.yml and re-run."
  fi
  # tar restores the repo's 0644 on every sync, so re-tighten the credential
  # files HERE (first boot + every update). Authelia runs as root in
  # container, so 600 root:root stays readable by it.
  sudo chmod 600 "$target/authelia/users_database.yml"   # argon2 master-password hashes
  # db.sqlite3 (TOTP seeds) is runtime data the tar never touches; tighten it
  # once it exists.
  if [[ -f "$target/authelia/db.sqlite3" ]]; then
    sudo chmod 600 "$target/authelia/db.sqlite3"
  fi
}

stack_restart_if_configs_changed() { # <target-dir> — call AFTER `up -d`
  local target="$1"
  local f authelia_changed=0 traefik_changed=0 searxng_changed=0 services=()
  for f in authelia/configuration.yml authelia/users_database.yml; do
    if [[ -f "$STACK_CONFIG_SNAP/${f//\//_}" ]] && ! sudo cmp -s "$STACK_CONFIG_SNAP/${f//\//_}" "$target/$f"; then
      authelia_changed=1
    fi
  done
  if [[ -f "$STACK_CONFIG_SNAP/traefik_traefik.yml" ]] \
     && ! sudo cmp -s "$STACK_CONFIG_SNAP/traefik_traefik.yml" "$target/traefik/traefik.yml"; then
    traefik_changed=1
  fi
  # searxng/settings.yml is start-time-only — a secret rotation or any other
  # content change restarts (does not recreate) the container. No snapshot on
  # first landing: the container was created fresh by the `up -d` above.
  if [[ -f "$STACK_CONFIG_SNAP/searxng_settings.yml" ]] \
     && ! sudo cmp -s "$STACK_CONFIG_SNAP/searxng_settings.yml" "$target/searxng/settings.yml"; then
    searxng_changed=1
  fi
  if (( authelia_changed || traefik_changed || searxng_changed )); then
    if (( authelia_changed )); then services+=(authelia); fi
    if (( traefik_changed )); then services+=(traefik); fi
    if (( searxng_changed )); then services+=(searxng); fi
    info "Config content changed — restarting ${services[*]} (read only at container start, no hot reload)"
    sudo docker compose --project-directory "$target" -f "$target/docker-compose.yml" restart "${services[@]}"
  fi
}

# ── ACME staging → production promotion ─────────────────────────────────────
# Used by 02-deploy-stack.sh (auto, after the stack is up) and
# 06-acme-promote.sh (manual). First bring-up runs on LE staging so DNS-01
# debugging can't hit prod's 5-failures/hour rate limit.

ACME_STAGING_URL="https://acme-staging-v02.api.letsencrypt.org/directory"
ACME_PROD_URL="https://acme-v02.api.letsencrypt.org/directory"

acme_mode() { # <deployed-traefik.yml> → echo: staging | prod | unknown
  local f="$1"
  if [[ ! -f "$f" ]]; then
    echo unknown
  elif sudo grep -q "$ACME_STAGING_URL" "$f"; then
    echo staging
  elif sudo grep -q "$ACME_PROD_URL" "$f"; then
    echo prod
  else
    echo unknown
  fi
}

acme_cert_issued() { # <target-dir> → exit 0 if the ACME store already holds a cert
  # v3 store layout: {<resolverName>: {"Certificates": [...]}} — a map keyed
  # by the certificatesResolvers name, "Certificates" an untagged Go field.
  # Accept any resolver name.
  sudo docker compose --project-directory "$1" -f "$1/docker-compose.yml" \
    exec -T traefik cat /letsencrypt/acme.json 2>/dev/null \
    | python3 -c 'import json,sys
try:
    d = json.load(sys.stdin)
except Exception:
    sys.exit(1)  # no store yet (or traefik down) — nothing issued
certs = [v.get("Certificates") for v in d.values() if isinstance(v, dict)]
sys.exit(0 if any(certs) else 1)'
}

acme_wait_for_cert() { # <target-dir> <timeout-seconds> — poll until a cert lands
  local deadline=$(( $(date +%s) + $2 ))
  while (( $(date +%s) < deadline )); do
    acme_cert_issued "$1" && return 0
    sleep 10
  done
  acme_cert_issued "$1"
}

acme_promote() { # <target-dir> — flip staging→prod. Idempotent; wipes the ACME store.
  local target="$1"
  local mode
  mode="$(acme_mode "$target/traefik/traefik.yml")"
  if [[ "$mode" == prod ]]; then
    info "ACME already on production — nothing to promote"
    return 0
  fi
  [[ "$mode" == staging ]] || die "cannot determine ACME mode from $target/traefik/traefik.yml"

  info "Checking the staging cert actually issued before promoting"
  acme_cert_issued "$target" \
    || die "no certificate in the ACME store yet — wait for issuance (make logs), then re-run"

  info "Staging cert issued ✓ — switching ACME to production"
  # Flip configs first: the running traefik only re-reads static config at
  # start, so this is inert until the restart below.
  sudo sed -i "s|$ACME_STAGING_URL|$ACME_PROD_URL|g" "$target/traefik/traefik.yml"
  if [[ -f "$REPO_ROOT/.env" ]]; then
    # Anchor to the assignment line — a global s/// would also rewrite the
    # staging/prod URLs in the .env comment block.
    sed -i "s|^ACME_CA_SERVER=.*|ACME_CA_SERVER=${ACME_PROD_URL}|" "$REPO_ROOT/.env"
    sudo install -m 600 "$REPO_ROOT/.env" "$target/.env"
  fi

  local compose=(sudo docker compose --project-directory "$target" -f "$target/docker-compose.yml")
  # The ACME store is staging-CA-specific: its account URI doesn't exist on
  # prod (reusing it fails JWS verification). Wipe it while traefik is down;
  # prod registers a fresh account.
  "${compose[@]}" stop traefik
  "${compose[@]}" run --rm -T --entrypoint /bin/sh traefik -c 'rm -f /letsencrypt/acme.json' \
    || warn "could not wipe the ACME store — if the prod cert never issues, remove it:\n         sudo docker run --rm -v panel_acme:/letsencrypt alpine rm -f /letsencrypt/acme.json"
  "${compose[@]}" up -d traefik

  info "Waiting for the production cert (usually a couple of minutes)"
  if acme_wait_for_cert "$target" "${ACME_PROMOTE_WAIT:-300}"; then
    info "production cert issued — https is trusted now (hard-refresh the browser)"
  else
    warn "no production cert after ${ACME_PROMOTE_WAIT:-300}s — traefik keeps retrying; check: make logs"
  fi
}

# ── Stack update / rollback (make update / make rollback) ────────────────────────
# `make update` (08-update.sh) is the one Day-2 command: apply the repo's
# configs (same sync as make deploy) AND float everything that has a *line* —
# container images on the major line, panel-web's base images, npm deps within
# package.json's ranges, panel-api's pip deps within requirements.txt. A
# MAJOR stays a deliberate edit (a tag, a FROM, a range). The rollout is
# wrapped in a safety net: doctor precondition → snapshot (image IDs
# re-tagged, config tree, exact panel-api copy, npm files) → npm bump + sync
# + pull → rebuild + converge → gate (post-update services healthy +
# panel-api serving + full doctor) → automatic rollback of all of it on
# failure. `make rollback` (09-rollback.sh) applies the rollback on demand;
# the state file always holds the *pre-update* snapshot. Details:
# docs/RUNBOOK.md → Updates.

STACK_STATE_FILE=/opt/panel/.update-state
STACK_LOCK_FILE=/opt/panel/.update.lock
ROLLBACK_TAG_PREFIX=portcullis-rollback
ROLLBACK_RETAIN_DAYS=14
SNAPSHOT_DIR_PREFIX=/opt/panel/.update-snapshot-   # + <ts>: panel-api copy + npm files

update_snapshot_dir() { # <ts> → that snapshot's dir
  echo "${SNAPSHOT_DIR_PREFIX}$1"
}

# Compose command for the deployed stack (project dir /opt/panel). Global so
# apply_snapshot() can append its override -f.
# The GPU pool override (panel-api's ledger projected as ROCR_VISIBLE_DEVICES
# per llm-* instance) is included in EVERY render
# on purpose: radiance floats on `latest`, so a routine `make update` can
# recreate running instances, and without the override that recreate would
# silently revert each instance to the card set committed in the base file.
# The file always exists — make deploy (02) creates it before the first
# `up -d`, make api (03) re-derives ownership, and panel-api re-renders it
# from the ledger on every change.
COMPOSE_STACK=(sudo docker compose --project-directory /opt/panel -f /opt/panel/docker-compose.yml -f /opt/panel-api/llm-gpu-override.yml)
stack_compose() { "${COMPOSE_STACK[@]}" "$@"; }

stack_services() { # every service defined in the deployed compose, one per line
  stack_compose config --format json \
    | python3 -c 'import json,sys
try:
    svcs = json.load(sys.stdin).get("services") or {}
except json.JSONDecodeError:
    sys.exit(1)
[print(s) for s in svcs]' \
    || die "cannot read the deployed compose config (missing env vars? re-run: make deploy)"
}

stack_pull_services() { # services with an `image:` key (build-only ones are skipped)
  stack_compose config --format json \
    | python3 -c 'import json,sys
try:
    svcs = json.load(sys.stdin).get("services") or {}
except json.JSONDecodeError:
    sys.exit(1)
[print(s) for s, v in svcs.items() if isinstance(v, dict) and v.get("image")]' \
    || die "cannot read the deployed compose config (missing env vars? re-run: make deploy)"
}

stack_image_ids() { # service → image ID of its running container (svc<TAB>id)
  # `docker compose images --format json` is deliberately avoided: its schema
  # has moved across compose releases. `ps` template + `inspect` is stable.
  local svc name id
  while IFS='|' read -r svc name; do
    [[ -n "${name:-}" ]] || continue
    id="$(sudo docker inspect --format '{{.Image}}' "$name" 2>/dev/null)" || continue
    printf '%s\t%s\n' "$svc" "$id"
  done < <(stack_compose ps --format '{{.Service}}|{{.Name}}' 2>/dev/null || true)
}

image_version_label() { # <image-id> → org.opencontainers.image.version label or ""
  sudo docker inspect --format '{{index .Config.Labels "org.opencontainers.image.version"}}' "$1" 2>/dev/null || true
}

update_acquire_lock() {
  # /opt/panel is root-owned, so the lock file is created (once, self-healing)
  # 666 — its content is irrelevant; only the flock matters.
  [[ -f "$STACK_LOCK_FILE" ]] || sudo install -m 666 /dev/null "$STACK_LOCK_FILE" \
    || die "cannot create lock file $STACK_LOCK_FILE"
  exec 9>>"$STACK_LOCK_FILE" || die "cannot open lock file $STACK_LOCK_FILE"
  flock -n 9 || die "another update/rollback is already running (lock: $STACK_LOCK_FILE — wait for it, or kill the other run)"
}

sudo_warm() { # re-warm the sudo timestamp so long operations don't prompt mid-run
  sudo -n true 2>/dev/null || sudo -v 2>/dev/null || true
}

update_set_status() { # <status: in-progress|updated|rolled-back|partially-rolled-back> — on the live state file
  local tmp
  tmp="$(mktemp)"
  python3 -c '
import json, sys
d = json.load(open(sys.argv[1]))
d["status"] = sys.argv[2]
json.dump(d, open(sys.argv[3], "w"), indent=2)
' "$STACK_STATE_FILE" "$1" "$tmp"
  sudo install -m 644 "$tmp" "$STACK_STATE_FILE"
  rm -f "$tmp"
}

update_gc_old_snapshots() { # prune rollback tags + snapshot dirs older than ROLLBACK_RETAIN_DAYS (never the live ones)
  local tag now created age live dir d ts live_dir
  [[ -f "$STACK_STATE_FILE" ]] || return 0
  now="$(date +%s)"
  live="$(python3 -c '
import json, sys
try:
    d = json.load(open(sys.argv[1]))
    [print(i["rollback_image"]) for i in d.get("services", {}).values()]
except Exception:
    pass' "$STACK_STATE_FILE" 2>/dev/null || true)"
  for tag in $(sudo docker image ls --filter "reference=${ROLLBACK_TAG_PREFIX}/*" \
      --format '{{.Repository}}:{{.Tag}}' 2>/dev/null); do
    [[ -n "$live" ]] && grep -Fqx "$tag" <<<"$live" && continue
    created="$(sudo docker image inspect --format '{{.Created}}' "$tag" 2>/dev/null)" || continue
    created_s="$(date -d "$created" +%s 2>/dev/null)" || continue   # unknown age → skip, never guess "old"
    age=$(( now - created_s ))
    if (( age > ROLLBACK_RETAIN_DAYS * 86400 )) \
       && sudo docker rmi "$tag" >/dev/null 2>&1; then
      info "Pruned old rollback tag $tag (older than ${ROLLBACK_RETAIN_DAYS} days)"
    fi
  done
  # Snapshot dirs — same retention, keyed by the ts in the name; never the live one.
  live_dir="$(update_snapshot_dir "$(python3 -c '
import json, sys
try:
    print(json.load(open(sys.argv[1])).get("snapshot", ""))
except Exception:
    pass' "$STACK_STATE_FILE" 2>/dev/null)")"
  for dir in /opt/panel/.update-snapshot-*/; do
    [[ -d "$dir" ]] || continue
    d="${dir%/}"
    [[ -n "$live_dir" && "$d" == "$live_dir" ]] && continue
    ts="${d##"$SNAPSHOT_DIR_PREFIX"}"   # d is <prefix><ts> — the basename is NOT the ts
    # ts is UTC (date -u at snapshot time) — the trailing Z keeps the age math
    # exact regardless of the host's timezone.
    created="$(date -d "${ts:0:4}-${ts:4:2}-${ts:6:2}T${ts:9:2}:${ts:11:2}:${ts:13:2}Z" +%s 2>/dev/null)" || continue
    age=$(( now - created ))
    if (( age > ROLLBACK_RETAIN_DAYS * 86400 )) && sudo rm -rf "$d"; then
      info "Pruned old snapshot dir $d (older than ${ROLLBACK_RETAIN_DAYS} days)"
    fi
  done
}

# Snapshot the running stack: re-tag every running image (anchored on the
# image ID — tags move, IDs don't), write the state file, set $SNAPSHOT_TS.
# Services without a running container are skipped with a note — a later
# rollback simply leaves them as-is.
snapshot_stack() {
  local ts svc container image_id image_tags lines="" tmp
  ts="$(date -u +%Y%m%dT%H%M%SZ)"
  for svc in $(stack_services); do
    container="$(stack_compose ps --format '{{.Service}}|{{.Name}}|{{.State}}' 2>/dev/null \
      | awk -F'|' -v s="$svc" '$1==s && $3=="running" {print $2; exit}' || true)"
    if [[ -z "$container" ]]; then
      warn "no running container for $svc — excluded from the rollback snapshot"
      continue
    fi
    image_id="$(sudo docker inspect --format '{{.Image}}' "$container")" \
      || die "cannot read the running image of $container ($svc)"
    # The image's repo:tag(s) at snapshot time, space-joined. Captured BEFORE
    # the rollback tag is added, so it records the upstream identity (the tag
    # itself moves on the next pull). `make rollback WHAT=<image-name>`
    # matches on this; an image without a repo tag records none.
    image_tags="$(sudo docker inspect --format '{{range .RepoTags}}{{.}} {{end}}' "$image_id" 2>/dev/null || true)"
    sudo docker tag "$image_id" "${ROLLBACK_TAG_PREFIX}/${svc}:${ts}" \
      || die "cannot tag $image_id as ${ROLLBACK_TAG_PREFIX}/${svc}:${ts}"
    lines+="${svc}|${image_id}|${ROLLBACK_TAG_PREFIX}/${svc}:${ts}|${image_tags}"$'\n'
  done
  tmp="$(mktemp)"
  printf '%s' "$lines" | python3 -c '
import json, sys
svcs = {}
for line in sys.stdin:
    line = line.strip()
    if line:
        parts = line.split("|")
        svcs[parts[0]] = {"image_id": parts[1], "rollback_image": parts[2],
                          "image_tags": parts[3] if len(parts) > 3 else ""}
json.dump({"snapshot": sys.argv[1], "status": "in-progress", "services": svcs},
          open(sys.argv[2], "w"), indent=2)
' "$ts" "$tmp"
  sudo install -m 644 "$tmp" "$STACK_STATE_FILE"
  rm -f "$tmp"
  # Global consumed by setup/08-update.sh (which sources this file) —
  # invisible to a per-file shellcheck run.
  # shellcheck disable=SC2034
  SNAPSHOT_TS="$ts"
}

# Wait until every expected service is running (and healthy, if it defines a
# healthcheck). 0 on success; 1 on dead/restarting/unhealthy or timeout — the
# reason lands in $HEALTH_GATE_REASON. Reads the full container list (--all):
# without it, a crash-looping service is invisible and reads as "no container
# yet", burning the whole budget. A serving (running + healthy/none)
# container passes over any stale remnant.
wait_stack_healthy() { # <timeout-seconds> <expected service...>
  local timeout="$1"; shift
  local deadline out verdict
  deadline=$(( $(date +%s) + timeout ))
  while :; do
    sudo_warm
    out="$(stack_compose ps --all --format json 2>/dev/null || true)"
    # env var, not a pipe: the heredoc below already owns python's stdin.
    # A crash here means the ps output is unparseable (compose too old /
    # format changed) — fail fast instead of burning the whole budget.
    if ! verdict="$(PS_JSON="$out" python3 - "$@" <<'PYEOF'
import json, os, sys
text = os.environ.get("PS_JSON", "").strip()
try:
    data = json.loads(text) if text else []
except json.JSONDecodeError:
    data = [json.loads(l) for l in text.splitlines() if l.strip()]
if not isinstance(data, list):
    data = [data]
rows = {}
for x in data:
    if isinstance(x, dict) and x.get("Service"):
        rows.setdefault(x["Service"], []).append(
            (x.get("State") or "unknown", x.get("Health") or "none"))
bad, pending = [], []
for s in sorted(sys.argv[1:]):
    cs = rows.get(s)
    if not cs:
        pending.append(s + " (no container yet)")
        continue
    if any(st == "running" and h in ("healthy", "none") for st, h in cs):
        continue
    dead = [f"{s} ({st})" for st, _ in cs
            if st in ("exited", "dead", "restarting", "paused")]
    if dead:
        bad.extend(dead)
    elif any(h == "unhealthy" for _, h in cs):
        bad.append(f"{s} (unhealthy)")
    else:
        pending.append(s)
if bad:
    print("BAD\t" + "; ".join(bad))
elif pending:
    print("WAIT\t" + "; ".join(pending))
else:
    print("OK")
PYEOF
)"; then
      HEALTH_GATE_REASON="cannot parse the compose ps output (unexpected format — is the compose version too old?)"
      warn "health gate: $HEALTH_GATE_REASON"
      return 1
    fi
    case "$verdict" in
      OK*) HEALTH_GATE_REASON=""; return 0 ;;
      BAD*) HEALTH_GATE_REASON="${verdict#*$'\t'}"; warn "health gate: $HEALTH_GATE_REASON"; return 1 ;;
    esac
    if (( $(date +%s) >= deadline )); then
      HEALTH_GATE_REASON="timeout after ${timeout}s — ${verdict#*$'\t'}"
      warn "health gate: $HEALTH_GATE_REASON"
      return 1
    fi
    sleep 10
  done
}

# Recreate the snapshot's services from the rollback tags in <state-file>, via
# a temporary compose override (the deployed compose file is never modified).
# With <service...>, only those services (a targeted rollback). 0 on success
# (re-gated); 1 on failure — the override file is kept for manual use.
apply_snapshot() { # <state-file> <timeout-seconds> [service...]
  local state="$1" timeout="$2"; shift 2
  local override pairs svc tag svcs=() missing=()
  sudo_warm
  override="$(mktemp /tmp/portcullis-rollback.XXXXXX.yml)"
  pairs="$(python3 - "$state" "$@" <<'PYEOF'
import json, sys
d = json.load(open(sys.argv[1]))
want = sys.argv[2:] or None
for s, i in d.get("services", {}).items():
    if want is not None and s not in want:
        continue
    print(s + "\t" + i["rollback_image"])
PYEOF
)"
  [[ -n "$pairs" ]] || die "no snapshot services match the rollback selection — nothing to roll back"
  while IFS=$'\t' read -r svc tag; do
    svcs+=("$svc")
    sudo docker image inspect "$tag" >/dev/null 2>&1 || missing+=("$tag")
  done <<<"$pairs"
  if (( ${#missing[@]} > 0 )); then
    rm -f "$override"
    die "rollback image(s) missing locally — the snapshot is unusable (were the tags pruned?):
  ${missing[*]}"
  fi
  printf '%s\n' "$pairs" | python3 -c '
import sys
print("services:")
for line in sys.stdin:
    svc, tag = line.rstrip("\n").split("\t")
    print(f"  {svc}:")
    print(f"    image: {tag}")
' >"$override"
  local -a cmd=("${COMPOSE_STACK[@]}" -f "$override")
  info "Restoring snapshot images for: ${svcs[*]}"
  # --remove-orphans drops containers for services ADDED during the failed
  # update (no longer in the restored compose file). Deliberately stopped
  # services are still in the file, so their (stopped) containers are kept.
  "${cmd[@]}" up -d --force-recreate --remove-orphans "${svcs[@]}"
  if wait_stack_healthy "$timeout" "${svcs[@]}"; then
    rm -f "$override"
    return 0
  fi
  warn "rollback re-gate failed — override kept at $override for manual use"
  return 1
}

# ── Non-container update targets: panel-api (host service) + npm files ──────────
# `make update` covers the host-side half too: the panel-web frontend (build
# context synced by the config sync, npm deps bumped with
# `npm update --package-lock-only` within package.json's ranges) and panel-api
# (main.py + requirements.txt + unit re-deployed, pip --upgrade within
# requirements.txt's ranges, restarted). Both are snapshotted and rolled back
# with the rest. panel-do / panel-ddns are stdlib-only — nothing to float.

# Snapshot the non-image update targets into <snapshot-dir>: the deployed
# config tree (panel.tar, runtime data excluded) + panel-api/ +
# panel-api.service + the npm files. Called before anything is touched, so a
# missing piece simply means "not updated yet" — rollback skips it.
snapshot_host_stack() { # <snapshot-dir>
  local dir="$1" fe m
  fe="$REPO_ROOT/compose/panel-frontend"
  sudo mkdir -p "$dir/npm" || die "cannot create snapshot dir $dir"
  # The snapshot holds secrets (panel.tar carries .env + the reduced env
  # files) — root-only, mirroring the deployed originals. The rollback
  # functions run as the deployer, not root, so they access it via sudo.
  sudo chmod 700 "$dir"
  if [[ -d /opt/panel-api ]]; then
    # Exact copy, venv included: what makes the panel-api rollback offline.
    sudo cp -a /opt/panel-api "$dir/panel-api" \
      || die "cannot snapshot /opt/panel-api into $dir (disk full?)"
    sudo cp -a /etc/systemd/system/panel-api.service "$dir/panel-api.service" 2>/dev/null || true
  fi
  # The lockfile is gitignored server-local state — snapshot it only if this
  # server has generated one yet.
  sudo cp -a "$fe/package.json" "$dir/npm/" \
    || die "cannot snapshot the npm files ($fe) into $dir"
  if [[ -f "$fe/package-lock.json" ]]; then
    sudo cp -a "$fe/package-lock.json" "$dir/npm/" \
      || die "cannot snapshot the npm files ($fe) into $dir"
  fi
  # The deployed config tree — a tarball so rollback restores it as a unit.
  # Explicit members only, so runtime data is never in it: authelia/db.sqlite3
  # (TOTP seeds) and panel-frontend's node_modules/dist.
  local members=()
  for m in docker-compose.yml traefik portfolio searxng authelia/configuration.yml \
           authelia/users_database.yml panel-frontend .env .panel-api.env \
           .panel-ddns.env; do
    # if, not `[[ ]] &&`: when the test fails the &&-list is the loop body's
    # last command and leaves the loop's exit status at 1.
    if [[ -e "/opt/panel/$m" ]]; then members+=("$m"); fi
  done
  if (( ${#members[@]} > 0 )); then
    sudo tar -C /opt/panel --exclude=panel-frontend/node_modules --exclude=panel-frontend/dist \
      -cf "$dir/panel.tar" "${members[@]}" \
      || die "cannot snapshot the deployed config tree into $dir (disk full?)"
    sudo chmod 600 "$dir/panel.tar"   # .env + the reduced env files inside — not for other users
  fi
}

# Bump the panel frontend's npm deps within the declared ranges (package.json
# untouched by design). No lockfile (fresh clone) → generate it from the
# ranges instead. Runs before the pull so a failure touches nothing.
npm_bump_panel_frontend() {
  local fe out
  fe="$REPO_ROOT/compose/panel-frontend"
  if [[ ! -f "$fe/package-lock.json" ]]; then
    if ! out="$(cd "$fe" && npm install --package-lock-only 2>&1)"; then
      warn "$out"
      die "npm install --package-lock-only failed — the running stack is untouched; fix the registry/network issue and re-run: make update"
    fi
    info "npm: no lockfile on this server yet — generated it from the declared ranges (server-local state, not committed)"
    return 0
  fi
  # --package-lock-only: a plain `npm update` also materializes node_modules
  # (~100 MB) in the repo dir — the build runs in Docker, so it serves no
  # purpose there.
  if ! out="$(cd "$fe" && npm update --package-lock-only 2>&1)"; then
    warn "$out"
    die "npm update failed — the running stack is untouched; fix the registry/network issue and re-run: make update"
  fi
  info "npm: $(tail -n1 <<<"$out")"
}

# Wait for panel-api to be active and serving (0 yes; 1 no — reason in
# $PANEL_API_REASON).
wait_panel_api_healthy() { # <timeout-seconds>
  local timeout="$1" deadline h
  deadline=$(( $(date +%s) + timeout ))
  while :; do
    if systemctl is-active --quiet panel-api 2>/dev/null; then
      h="$(curl -s --max-time 5 http://172.17.0.1:8010/api/health 2>/dev/null || true)"
      if grep -q '"ok":true' <<<"$h"; then
        PANEL_API_REASON=""
        return 0
      fi
    fi
    if (( $(date +%s) >= deadline )); then
      PANEL_API_REASON="panel-api not active or /api/health not ok after ${timeout}s (check: systemctl status panel-api)"
      warn "panel-api: $PANEL_API_REASON"
      return 1
    fi
    sleep 3
  done
}

# Update the deployed panel-api in place: new main.py + llm_gpus.py +
# llm_autostart.py + requirements.txt + both units, pip --upgrade within the
# declared ranges, restart, verify serving. The GPU pool state files (ledger
# + override) are NOT touched — they are runtime data owned by panel-api and
# ride the snapshot's whole /opt/panel-api copy for rollback.
# Deliberately does NOT re-run 03-panel-api.sh: its UFW gate is first-install
# protection; on an already-deployed server a firewall regression surfaces in
# the doctor gate → auto-rollback.
update_panel_api() {
  PANEL_API_REASON=""
  local f
  for f in main.py llm_gpus.py llm_autostart.py requirements.txt; do
    sudo cp -a "$REPO_ROOT/panel-api/$f" /opt/panel-api/ \
      || { PANEL_API_REASON="cannot install $f into /opt/panel-api"; return 1; }
  done
  sudo chown -R panel:panel /opt/panel-api \
    || { PANEL_API_REASON="chown /opt/panel-api failed"; return 1; }
  sudo cp -a "$REPO_ROOT/panel-api/panel-api.service" /etc/systemd/system/panel-api.service \
    || { PANEL_API_REASON="cannot install panel-api.service"; return 1; }
  # Fleet boot autostart: (re)install + keep enabled so an update to this
  # repo's unit definition is applied (make api already enabled it; enabling
  # again is idempotent). A no-op at boot when the autostart list is empty.
  sudo cp -a "$REPO_ROOT/panel-api/llm-autostart.service" /etc/systemd/system/llm-autostart.service \
    || { PANEL_API_REASON="cannot install llm-autostart.service"; return 1; }
  sudo systemctl daemon-reload \
    || { PANEL_API_REASON="systemctl daemon-reload failed"; return 1; }
  sudo systemctl enable llm-autostart \
    || { PANEL_API_REASON="enable llm-autostart failed"; return 1; }
  # --upgrade floats within requirements.txt's ranges (>=x,<MAJOR) and
  # converges if the installed set violates them.
  sudo -u panel /opt/panel-api/venv/bin/pip install --quiet --upgrade -r /opt/panel-api/requirements.txt \
    || { PANEL_API_REASON="pip install --upgrade failed (registry/network?)"; return 1; }
  sudo systemctl restart panel-api \
    || { PANEL_API_REASON="systemctl restart panel-api failed"; return 1; }
  wait_panel_api_healthy 60 || return 1
  return 0
}

# Restore the snapshot's exact panel-api copy (venv included → offline).
# 0 ok (or not in snapshot); 1 failed.
rollback_panel_api() { # <snapshot-dir>
  local dir="$1"
  # The snapshot dir is root:root 700 and this runs as the deployer — sudo
  # the existence tests: a user-side [[ -d ]] fails EACCES (not ENOENT) and
  # would misreport "not in snapshot", silently skipping the restore.
  if ! sudo test -d "$dir/panel-api"; then
    info "  panel-api: not in snapshot — skipped"
    return 0
  fi
  info "  panel-api: restoring the snapshot copy"
  sudo systemctl stop panel-api 2>/dev/null || true
  sudo rm -rf /opt/panel-api
  sudo cp -a "$dir/panel-api" /opt/panel-api || { warn "  panel-api: restore copy failed"; return 1; }
  if sudo test -f "$dir/panel-api.service"; then
    sudo cp -a "$dir/panel-api.service" /etc/systemd/system/panel-api.service
  fi
  sudo systemctl daemon-reload 2>/dev/null || true
  # The explicit stop above means Restart=on-failure won't bring the unit
  # back — start it, then verify it serves the OLD code.
  if ! sudo systemctl start panel-api 2>/dev/null; then
    warn "  panel-api: copy restored but systemctl start failed — check: systemctl status panel-api"
    return 1
  fi
  if wait_panel_api_healthy 60; then
    info "  panel-api: restored and serving"
    return 0
  fi
  warn "  panel-api: restored but not serving — check: systemctl status panel-api"
  return 1
}

# Restore the snapshot's deployed config tree (see snapshot_host_stack). Must
# run BEFORE the image recreate: the rollback's `compose up` then reads the
# pre-update compose file + .env. Runtime data is not in the tar. Files
# created under /opt/panel during the update are left in place — inert: the
# restored compose no longer defines them. 0 ok (or not in snapshot); 1 failed.
rollback_stack_configs() { # <snapshot-dir>
  local dir="$1"
  # sudo the test: root-only snapshot dir — a user-side [[ -f ]] fails EACCES
  # → "not in snapshot" on every rollback (see rollback_panel_api).
  if ! sudo test -f "$dir/panel.tar"; then
    info "  configs: not in snapshot — skipped"
    return 0
  fi
  info "  configs: restoring the pre-update /opt/panel files"
  if sudo tar -C /opt/panel -xf "$dir/panel.tar"; then
    return 0
  fi
  warn "  configs: restore failed — the deployed configs may still be the post-update ones"
  return 1
}

# Restore the snapshot's npm files in the repo. 0 ok (or not in snapshot).
rollback_npm() { # <snapshot-dir>
  local dir="$1" fe f tmp
  fe="$REPO_ROOT/compose/panel-frontend"
  # sudo the tests (root-only snapshot dir). The copies must go through a
  # user-owned temp: a user cp can't read the dir, and a direct sudo cp would
  # leave root-owned files in the deployer's repo.
  if ! sudo test -f "$dir/npm/package.json"; then
    info "  npm: not in snapshot — skipped"
    return 0
  fi
  for f in package.json package-lock.json; do   # lockfile only if this server generated one
    sudo test -f "$dir/npm/$f" || continue
    tmp="$(mktemp)"
    # no -a: a root `cp -a` chowns the tmpfile to the source's owner — a
    # root-owned repo file would leak into /tmp undeletable by the user.
    if sudo cp "$dir/npm/$f" "$tmp" && install -m 644 "$tmp" "$fe/$f"; then
      rm -f "$tmp"
    else
      warn "  npm: $f restore failed"
      rm -f "$tmp"
      return 1
    fi
  done
  info "  npm: package.json restored (+ package-lock.json, if it was snapshotted)"
  return 0
}

# Auto-rollback + hard stop — used by 08-update.sh when a gate fails. Rolls
# back everything the update touched, best-effort per component. Never returns.
update_rollback_or_die() { # <reason>
  local reason="$1" ts dir failed=()
  warn "gate failed: $reason"
  warn "rolling back to the pre-update snapshot (budget ${UPDATE_HEALTH_TIMEOUT:-600}s)"
  sudo -v
  ts="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get("snapshot",""))' "$STACK_STATE_FILE" 2>/dev/null)" \
    || die "cannot read the snapshot ts from $STACK_STATE_FILE — manual intervention needed"
  [[ -n "$ts" ]] || die "state file $STACK_STATE_FILE holds no snapshot ts — manual intervention needed"
  dir="$(update_snapshot_dir "$ts")"
  # Configs first: the image recreate below must read the PRE-UPDATE compose
  # file + .env (the restored ones).
  rollback_stack_configs "$dir" || failed+=("configs")
  # Subshell: apply_snapshot's die (e.g. rollback image pruned) must not abort
  # the remaining rollbacks — record it as a failed component instead.
  ( apply_snapshot "$STACK_STATE_FILE" "${UPDATE_HEALTH_TIMEOUT:-600}" ) || failed+=("container images")
  rollback_panel_api "$dir" || failed+=("panel-api")
  rollback_npm "$dir" || failed+=("npm files")
  if (( ${#failed[@]} == 0 )); then
    update_set_status rolled-back
    die "update FAILED and the stack was reverted to the pre-update snapshot.
Investigate, then re-run: make update
  make logs     # the failing service's logs are the place to start
  make doctor   # confirm everything is fully green again"
  fi
  # leave the status as "in-progress": the stack's state is unknown here and a
  # later `make update`/`make rollback` will rewrite it.
  die "update FAILED and the automatic rollback was PARTIAL — not reverted: ${failed[*]}
Manual intervention needed (the remaining snapshots are intact — see docs/RUNBOOK.md → Updates).
Snapshot dir: $dir  (panel-api copy + npm files)
Rollback images: sudo docker image ls  (tags ${ROLLBACK_TAG_PREFIX}/*)
State file: $STACK_STATE_FILE"
}

# Old→new per-service report: state file (what was running) vs current images.
report_stack_update() { # <state-file> <after-ids-file>
  local state="$1" after="$2" svc old new ov nv st
  printf '  %-13s %-16s %-16s %s\n' service before after status
  while IFS=$'\t' read -r svc old; do
    new="$(awk -F'\t' -v s="$svc" '$1==s {print $2; exit}' "$after")"
    ov="$(image_version_label "$old")"; ov="${ov:-${old:7:12}}"
    if [[ -z "$new" ]]; then
      nv="—"; st="image missing after update?!"
    elif [[ "$new" == "$old" ]]; then
      nv="$ov"; st="unchanged"
    else
      nv="$(image_version_label "$new")"; nv="${nv:-${new:7:12}}"
      st="changed"
    fi
    printf '  %-13s %-16s %-16s %s\n' "$svc" "$ov" "$nv" "$st"
  done < <(python3 -c '
import json, sys
for s, i in json.load(open(sys.argv[1]))["services"].items():
    print(s + "\t" + i["image_id"])' "$state")
}
